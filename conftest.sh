#!/bin/sh
# Probe the target kernel's API and print a C header to stdout.
#
# Each conftest/<name>.c is a small snippet that compiles only if a kernel
# feature is present. All probes are compiled in a single Kbuild run, using
# the target kernel's own flags, and each resulting .o becomes
# "#define HAVE_<NAME>".
#
# A probe can also fail for an unrelated reason (a typo, a missing include),
# which selects the fallback code. Only rely on a probe where the fallback
# then fails to compile (e.g. a mismatched signature or a missing member).
# Compiler output is kept in conftest/conftest.log.
#
# Usage: conftest.sh <kernel build dir>

kdir=$1
dir=$(cd "$(dirname "$0")/conftest" && pwd)
probes=$(cd "$dir" && ls *.c | sed 's/\.c$/.o/')

rm -f "$dir"/*.o
make -k -C "$kdir" M="$dir" $probes > "$dir/conftest.log" 2>&1

echo "/* Generated by conftest.sh for $kdir. Do not edit. */"
for o in $probes; do
    if [ -f "$dir/$o" ]; then
        echo "#define HAVE_$(basename "$o" .o | tr a-z A-Z)"
    fi
done
